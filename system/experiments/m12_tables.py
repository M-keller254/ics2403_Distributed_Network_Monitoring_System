"""Render the capstone summary (results/m12_capstone_summary.csv) as markdown tables -> results/m12_tables.md.
Every number in docs/milestones/12-capstone.md and docs/technical-report.md is copied from this file, not typed by hand.

Run:  python -m system.experiments.m12_tables
"""
import os

import pandas as pd

from system.experiments.common import RESULTS

SYS = ["baseline-flat", "proposed", "proposed+improved"]
SHORT = {"baseline-flat": "baseline", "proposed": "proposed", "proposed+improved": "improved"}

# (title, sweep, metric column prefix, decimals, unit)
BLOCKS = [
    ("bandwidth", [("complete_s", 2, "time to deliver all 120,000 rows (s)"), ("wire_mb", 1, "bytes on the edge→core link (MB)"), ("cpu_pct_mean", 0, "mean CPU % of core/collector"), ("req_lat_p95_ms", 1, "request latency p95 (ms)")]),
    ("failure_rate", [("ingest_availability_pct", 1, "ingest availability % (100 ms write probe)"), ("mttr_resume_s", 2, "MTTR (s): crash → accepting writes again"), ("request_failure_rate_pct", 2, "failed requests %"), ("rows_lost", 0, "rows lost"), ("complete_s", 1, "time to deliver 60,000 rows at 4,000 rows/s (s)")]),
    ("users", [("req_lat_p95_ms", 1, "request latency p95 (ms)"), ("jitter_rfc3550_ms", 2, "jitter, RFC-3550 style (ms)"), ("e2e_rows_s", 0, "end-to-end throughput (rows/s)"), ("rss_mb_mean", 0, "resident memory (MB)")]),
    ("nodes", [("e2e_rows_s", 0, "end-to-end throughput (rows/s)"), ("cpu_pct_mean", 0, "mean CPU % of core processes"), ("rss_mb_mean", 0, "resident memory (MB)")]),
    ("cpu", [("e2e_rows_s", 0, "end-to-end throughput (rows/s)"), ("req_lat_p95_ms", 1, "request latency p95 (ms)")]),
    ("memory", [("complete_s", 1, "time to complete 60,000 rows (s)"), ("rows_lost", 0, "rows lost"), ("rss_mb_mean", 0, "resident memory (MB)")]),
    ("net_load", [("complete_s", 2, "time to complete (s)"), ("req_lat_p95_ms", 1, "request latency p95 (ms)"), ("jitter_rfc3550_ms", 2, "jitter (ms)")]),
    ("request_rate", [("complete_s", 2, "time to complete (s)"), ("req_lat_p95_ms", 1, "request latency p95 (ms)")]),
    ("data_volume", [("complete_s", 2, "time to complete (s)"), ("e2e_rows_s", 0, "end-to-end throughput (rows/s)"), ("wire_mb", 2, "bytes on the link (MB)")]),
]


def fmt(row, col, dec):
    if row is None or pd.isna(row.get(col)):
        return "–"
    m = row[col]
    sd = row.get(col.replace("_mean", "") + "_sd", row.get(col + "_sd"))
    txt = f"{m:.{dec}f}" if dec else f"{m:,.0f}"
    if sd is not None and not pd.isna(sd) and sd > 0 and dec is not None:
        txt += f" ±{sd:.{dec}f}" if dec else f" ±{sd:,.0f}"
    return txt


def table(df, sweep, col, dec, title):
    d = df[df.sweep == sweep].sort_values("level_order")
    lv = list(d["level"].drop_duplicates())
    lines = [f"**{title}**", "", "| level | " + " | ".join(SHORT[s] for s in SYS) + " |", "|---|" + "---|" * len(SYS)]
    for l in lv:
        cells = []
        for s in SYS:
            r = d[(d.level == l) & (d.system == s)]
            cells.append(fmt(r.iloc[0].to_dict() if len(r) else None, col + "_mean" if col + "_mean" in d.columns else col, dec))
        lines.append(f"| {l} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main():
    df = pd.read_csv(os.path.join(RESULTS, "m12_capstone_summary.csv"))
    df["level"] = df["level"].astype(str)
    out = ["# Capstone tables (generated by `python -m system.experiments.m12_tables`; mean ±sd over `reps` repetitions)\n"]
    for sweep, metrics in BLOCKS:
        out.append(f"## Sweep: {sweep}\n")
        for col, dec, title in metrics:
            out.append(table(df, sweep, col, dec, title))
    raw = pd.read_csv(os.path.join(RESULTS, "m12_capstone_raw.csv"))
    raw = raw[raw["error"].isna()] if "error" in raw else raw
    raw["cpu_s"] = raw.cpu_pct_mean / 100 * raw.complete_s
    for sweep, order in (("bandwidth", ["unlimited", "100", "25", "10", "5"]),):
        g = raw[raw.sweep == sweep].assign(level=lambda d: d.level.astype(str)).groupby(["level", "system"]).cpu_s.mean().unstack("system").reindex(order)
        out.append(f"## Derived: total CPU-seconds of the core/collector processes (mean CPU % x time), sweep {sweep}\n")
        out.append("| level | baseline | proposed | improved |\n|---|---|---|---|")
        for lv, r in g.iterrows():
            out.append(f"| {lv} | {r['baseline-flat']:.2f} | {r['proposed']:.2f} | {r['proposed+improved']:.2f} |")
        out.append("")
    t = df[df.sweep == "transport"]
    out.append("## Sweep: transport (proposed system, 12 core crashes per minute, 4,000 rows/s)\n")
    out.append("| transport | complete (s) | p95 latency (ms) | availability % | MTTR (s) | rows lost | CPU % |\n|---|---|---|---|---|---|---|")
    for _, r in t.iterrows():
        out.append(f"| {r['level']} | {r['complete_s_mean']:.2f} | {r['req_lat_p95_ms_mean']:.1f} | {r['ingest_availability_pct_mean']:.1f} | {r['mttr_resume_s_mean']:.2f} | {r['rows_lost_mean']:.0f} | {r['cpu_pct_mean_mean']:.1f} |")
    open(os.path.join(RESULTS, "m12_tables.md"), "w").write("\n".join(out) + "\n")
    print("saved results/m12_tables.md")


if __name__ == "__main__":
    main()
